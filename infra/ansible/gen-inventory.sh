#!/usr/bin/env bash
# Generate the Ansible inventory from the node list, so addresses live in one place (decision D9).
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
CONF=${NODES_CONF:-$HERE/../libvirt/nodes.conf}
OUT=$HERE/inventory/hosts.ini
rows() { grep -v '^[[:space:]]*#' "$CONF" | grep -v '^[[:space:]]*$'; }
{
  echo "# Generated by gen-inventory.sh from infra/libvirt/nodes.conf. Do not edit."
  echo "[control]"; rows | awk '$2=="control" {printf "%s ansible_host=%s\n",$1,$3}'
  echo; echo "[workers]"; rows | awk '$2=="worker" {printf "%s ansible_host=%s\n",$1,$3}'
  echo; echo "[cluster:children]"; echo "control"; echo "workers"
} > "$OUT"
echo "wrote $OUT"
